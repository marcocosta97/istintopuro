#!/usr/bin/env python3
"""Keep the static quiz entry in sync with the app; stamp both pages for release."""

import argparse
import re
from html import escape
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
QUIZ_TITLE = "Quiz di calcio giornaliero — Istinto Puro"
QUIZ_DESCRIPTION = (
    "Trova i calciatori che collegano le squadre: tre sfide al giorno e "
    "un’Impossibile facoltativa. Il quiz è uguale per tutti. Gioca gratis, senza account."
)


def quiz_page(source):
    page = source.replace('<html lang="it">', '<html lang="it" data-entry="quiz">', 1)
    page = page.replace('<head>', '<head>\n<!-- Generated by scripts/site-pages.py from site/index.html. -->\n<base href="../">', 1)
    page = re.sub(r"<title>.*?</title>", f"<title>{QUIZ_TITLE}</title>", page, count=1)
    for selector in ['name="description"', 'property="og:description"', 'name="twitter:description"']:
        page = re.sub(rf'(<meta {selector} content=")[^"]*',
                      lambda match: match[1] + escape(QUIZ_DESCRIPTION, quote=True), page, count=1)
    for selector in ['property="og:title"', 'property="og:image:alt"',
                     'name="twitter:title"', 'name="twitter:image:alt"']:
        page = re.sub(rf'(<meta {selector} content=")[^"]*',
                      lambda match: match[1] + escape(QUIZ_TITLE, quote=True), page, count=1)
    for selector, attribute in [('link rel="canonical"', 'href'), ('meta property="og:url"', 'content')]:
        page = re.sub(rf'(<{selector} {attribute}=")https://istintopuro.mcosta.it/',
                      r'\g<1>https://istintopuro.mcosta.it/quiz/', page, count=1)
    return page


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the quiz page is stale")
    parser.add_argument("--version", help="Stamp asset URLs in both HTML entry points for deployment")
    args = parser.parse_args()
    if args.check and args.version:
        parser.error("--check and --version cannot be combined")
    if args.version and not re.fullmatch(r"[A-Za-z0-9._-]+", args.version):
        parser.error("--version must be an asset-safe release identifier")

    home = SITE / "index.html"
    target = SITE / "quiz/index.html"
    source = home.read_text()
    generated = quiz_page(source)
    if args.check:
        if "__V__" not in source:
            parser.exit(1, "Source HTML is already stamped. Restore the __V__ placeholders before checking or committing.\n")
        if not target.exists() or target.read_text() != generated:
            parser.exit(1, "Quiz entry is stale. Run: python3 scripts/site-pages.py\n")
        print("Static quiz entry is up to date.")
        return
    if args.version:
        source = source.replace("__V__", args.version)
        generated = generated.replace("__V__", args.version)
        home.write_text(source)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generated)
    print("Generated site/quiz/index.html" + (f" (release {args.version})" if args.version else ""))


if __name__ == "__main__":
    main()
